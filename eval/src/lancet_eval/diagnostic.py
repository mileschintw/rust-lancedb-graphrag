"""Per-question diagnostic table: joins the live-store gold-chunk probe, the
run journal, and the corpus/document map into one regenerable yes/no table.

This module never computes ground truth itself. Column (a) comes from
`load_document_map`, column (b) comes from the `inspect_lancedb --gold-chunks`
probe output (JSONL, one line per evidence item), column (c)
comes from the `diag_probe --vector-top-k 4` output, columns (d)/seed count/path
found come from the `diag_probe --graph-seeds` output (D-75..D-79), and per-arm
outcomes come from the run journal via `load_records`. Everything here is
read-only: no function in this module writes to the eval store, the journal, or
the document map.
"""

from __future__ import annotations

import argparse
import json
import math
import re
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from lancet_eval.corpus import GoldQuestion, load_sample_questions
from lancet_eval.journal import RunRecord, load_records
from lancet_eval.metrics import answer_usable as _answer_usable
from lancet_eval.metrics import extract_final_answer
from lancet_eval.seed import load_document_map

_D69_MIXED = "answer basis 'mixed' requires at least one cited evidence ID"
_D69_RETRIEVAL = "answer basis 'retrieval' requires at least one cited evidence ID"
_D69_MODEL_ONLY = "ModelOnly answer basis is not supported"
_MARKER_MISMATCH = "mismatch between cited_evidence_ids"
_HARNESS_TIMEOUT_ERROR_TYPES = ("StreamDeadlineExceeded", "ReadTimeout")


def classify_record(record: RunRecord) -> str | None:
    """Classifies an errored journal record into a stable D-69/timeout/transport class.

    Returns None for a non-error outcome (nothing to classify). See RESEARCH
    §B for the exact message prefixes and the fixed classification order:
    a node `error_kind == 1` (timeout) takes priority over the D-69 message
    match, and a harness-level `error_type` is checked only when no
    node-level failure explains the error.
    """
    if record.outcome != "error":
        return None

    for node_failure in record.node_failures:
        if node_failure.error_kind == 1:
            return "timeout"
        if node_failure.node_name != "GenerateAnswer":
            continue
        message = node_failure.error_message
        if message.startswith(_D69_MIXED):
            return "citation_basis_mixed"
        if message.startswith(_D69_RETRIEVAL):
            return "citation_basis_retrieval"
        if message.startswith(_D69_MODEL_ONLY):
            return "model_only_unsupported"
        if message.startswith(_MARKER_MISMATCH):
            return "citation_marker_mismatch"

    if record.error_type in _HARNESS_TIMEOUT_ERROR_TYPES:
        return "timeout"
    if record.error_type is not None:
        return "transport"

    return "other"


class DiagnosticError(Exception):
    """Raised when diagnostic table inputs are internally inconsistent.

    Never silently resolved — for example, two journal records for the same
    (question_id, arm) pair raise rather than picking one arbitrarily.
    """


class ArmResult(BaseModel):
    """Per-arm (graph-on / graph-off) outcome and quality facts for one question."""

    model_config = ConfigDict(extra="forbid")

    arm: str
    outcome: Literal["success", "error", "not_run"]
    error_class: str | None = None
    answer_usable: bool | None = None
    final_answer_missing: bool | None = None
    final_answer: str | None = None


class DiagnosticRow(BaseModel):
    """One row of the required per-question diagnostic table.

    Regenerated by `build_rows`/`write_table`; never hand-edited.
    """

    model_config = ConfigDict(extra="forbid")

    question_id: str
    question_type: str
    is_null: bool
    a_gold_doc_in_map: bool | None
    b_items: list[str] = Field(default_factory=list)
    b_gold_chunk_in_lancedb: bool | None
    c_gold_in_vector_top4: bool | None = None
    d_graph_seed_hit: bool | None = None
    seed_count: int | None = None
    path_found: bool | None = None
    e_answer_usable: bool | None = None
    arms: dict[str, ArmResult] = Field(default_factory=dict)
    in_gold_in_index_subset: bool


def _load_gold_chunks_by_question(
    gold_chunks_path: str | Path,
) -> dict[str, list[dict]]:
    """Reads the `--gold-chunks` probe JSONL, grouped by `question_id`.

    Each value is the list of per-evidence-item records for that question,
    sorted by `evidence_index` (the probe already sorts by (question_id,
    evidence_index), but the sort is repeated here so this function is
    correct even against a hand-built or reordered fixture).
    """
    by_question: dict[str, list[dict]] = {}
    path = Path(gold_chunks_path)
    with open(path, encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue
            record = json.loads(stripped)
            by_question.setdefault(record["question_id"], []).append(record)
    for records in by_question.values():
        records.sort(key=lambda r: r["evidence_index"])
    return by_question


def _load_journal_header(journal_path: str | Path) -> dict | None:
    """Reads only the first line of a journal file, returning it if it is a header.

    Returns None if the file does not exist, is empty, or its first line is
    not a `{"type": "header", ...}` record.
    """
    path = Path(journal_path)
    if not path.is_file():
        return None
    with open(path, encoding="utf-8") as f:
        first_line = f.readline().strip()
    if not first_line:
        return None
    try:
        data = json.loads(first_line)
    except json.JSONDecodeError:
        return None
    if isinstance(data, dict) and data.get("type") == "header":
        return data
    return None


def _arms_by_question(
    records: list[RunRecord],
) -> tuple[list[str], dict[tuple[str, str], RunRecord]]:
    """Indexes journal records by (question_id, arm), raising on duplicates.

    Returns the sorted list of distinct arm names seen anywhere in the
    journal (used to synthesize `not_run` placeholders for questions with no
    record for a given arm) alongside the (question_id, arm) -> record index.
    """
    by_key: dict[tuple[str, str], RunRecord] = {}
    arms: set[str] = set()
    for record in records:
        key = (record.question_id, record.graph_arm)
        if key in by_key:
            raise DiagnosticError(
                f"duplicate journal record for question_id={record.question_id!r} "
                f"arm={record.graph_arm!r}; refusing to silently choose one"
            )
        by_key[key] = record
        arms.add(record.graph_arm)
    return sorted(arms), by_key


def _question_a(question: GoldQuestion, mapped_titles: set[str]) -> bool | None:
    """Column (a): every gold evidence title has a document_map entry.

    None for null questions (no evidence to check).
    """
    if question.is_null:
        return None
    return all(item.get("title") in mapped_titles for item in question.evidence_list)


def _question_b(items: list[dict]) -> tuple[list[str], bool | None]:
    """Column (b): every evidence item's gold chunk is `in_chunk` (D-63).

    `items` is the caller's pre-fetched per-question gold-chunks list (already
    `[]` for a null question or a question absent from the probe file). Returns
    `([], None)` when there are no items; b_items lists the raw per-item states
    in evidence_index order.
    """
    states = [item["state"] for item in items]
    if not states:
        return states, None
    return states, all(state == "in_chunk" for state in states)


def _load_vector_top4_by_question(
    vector_top4_path: str | Path,
) -> dict[str, list[str]]:
    """Reads the `--vector-top-k 4` probe JSONL, grouped by `question_id` -> chunk_ids.

    Skips the trailing summary line (`{spend_usd, questions, cached,
    stopped_by_cap}`, which carries no `question_id`) and defensively
    truncates to the first 4 chunk_ids per question in case a caller ever
    points this at a `k > 4` probe run.
    """
    by_question: dict[str, list[str]] = {}
    path = Path(vector_top4_path)
    with open(path, encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue
            record = json.loads(stripped)
            question_id = record.get("question_id")
            if question_id is None:
                continue  # the trailing summary line
            by_question[question_id] = record.get("chunk_ids", [])[:4]
    return by_question


def _question_c(
    items: list[dict],
    top4_chunk_ids: list[str] | None,
) -> bool | None:
    """Column (c): any `in_chunk` evidence item's gold chunk is in the vector top-4.

    `None` when there is no vector-top4 file at all, or this question has no
    entry in it — a cap-stopped probe run leaves later questions absent, which
    must read as "not yet measured", never as "no". `False` when the question
    has a top-4 result but no `in_chunk` gold chunk exists to compare it
    against (e.g. every evidence item is `absent`/`split_across_chunks`).
    """
    if top4_chunk_ids is None:
        return None
    gold_chunk_ids: set[str] = set()
    for item in items:
        if item.get("state") == "in_chunk":
            gold_chunk_ids.update(item.get("chunk_ids", []))
    return any(chunk_id in gold_chunk_ids for chunk_id in top4_chunk_ids)


def _load_seed_probe(
    seed_probe_path: str | Path,
) -> tuple[dict[str, dict], dict | None]:
    """Reads the `diag_probe --graph-seeds` JSONL.

    Returns the per-question records keyed by `question_id` and the trailing
    summary line (the one record without a `question_id`; `None` when the file
    has none, as in a hand-built fixture).
    """
    by_question: dict[str, dict] = {}
    summary: dict | None = None
    path = Path(seed_probe_path)
    with open(path, encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue
            record = json.loads(stripped)
            question_id = record.get("question_id")
            if question_id is None:
                summary = record
            else:
                by_question[question_id] = record
    return by_question, summary


def _gold_document_ids(
    question: GoldQuestion, title_to_document_id: dict[str, str]
) -> set[str]:
    """Document IDs of a question's gold evidence, resolved by title through the map.

    A title with no map entry contributes nothing (column (a) already reports
    that case), so an unmapped title can never make column (d) read "yes".
    """
    ids: set[str] = set()
    for item in question.evidence_list:
        document_id = title_to_document_id.get(item.get("title", ""))
        if document_id is not None:
            ids.add(document_id)
    return ids


def _question_d(gold_document_ids: set[str], probe_record: dict) -> bool:
    """Column (d): a seed entity is sourced from a gold evidence document (D-79).

    A seed's `source_document_ids` come from its `source_chunk_ids` (the
    `{document_id}:{chunk_index}` prefix), so this is entity -> source chunk ->
    document, as D-79 defines it.
    """
    for seed in probe_record.get("seeds", []):
        if gold_document_ids.intersection(seed.get("source_document_ids", [])):
            return True
    return False


def compute_populations(rows: list[DiagnosticRow]) -> dict:
    """Computes G (gold-in-index subset, D-63) and V (G ∩ (c)=yes, D-82/D-63).

    G reuses `row.in_gold_in_index_subset` directly rather than re-deriving
    "non-null AND b" a second time, so G has exactly one definition across
    this module. `row.c_gold_in_vector_top4 is True` is required for V
    (not merely truthy) so a `None` — a question not yet measured by the (c)
    probe (e.g. a cap-stopped run) — is excluded from V rather than silently
    counted as a miss.
    """
    g_question_ids = {row.question_id for row in rows if row.in_gold_in_index_subset}
    v_question_ids = {
        row.question_id
        for row in rows
        if row.in_gold_in_index_subset and row.c_gold_in_vector_top4 is True
    }

    g_by_type: dict[str, int] = {}
    v_by_type: dict[str, int] = {}
    for row in rows:
        if row.question_id in g_question_ids:
            g_by_type[row.question_type] = g_by_type.get(row.question_type, 0) + 1
        if row.question_id in v_question_ids:
            v_by_type[row.question_type] = v_by_type.get(row.question_type, 0) + 1

    return {
        "g_question_ids": sorted(g_question_ids),
        "v_question_ids": sorted(v_question_ids),
        "g_count": len(g_question_ids),
        "v_count": len(v_question_ids),
        "g_by_type": g_by_type,
        "v_by_type": v_by_type,
    }


def build_rows(
    corpus_name: str,
    journal_path: str | Path | None,
    gold_chunks_path: str | Path,
    vector_top4_path: str | Path | None = None,
    seed_probe_path: str | Path | None = None,
) -> list[DiagnosticRow]:
    """Builds one DiagnosticRow per question in `corpus_name`'s sample.

    Columns (d)/seed_count/path_found are filled from `seed_probe_path` (the
    `diag_probe --graph-seeds` output, D-79) when it is given, and only for
    the questions that file covers: a question the probe did not measure stays
    `None`, never "no". (d) is `None` for a null question (no gold evidence to
    hit), while its `seed_count`/`path_found` are still recorded.
    `seed_probe_path=None` (the default) leaves all three `None` for every row.
    A graph-on journal record that carries the wire fields (`graph_seed_count`,
    `graph_path_found`, `graph_seed_document_ids`) overrides the probe field by
    field, so a drive's table reads what that drive's engine measured; a record
    that predates a field leaves the probe's value (or `None`) in place.
    Column (c) is computed here when `vector_top4_path` is given (the
    (c) join, RESEARCH §E/§F); `vector_top4_path=None` (the default) leaves
    (c) `None` for every row, so every existing caller of this function is
    unaffected. Per-arm `error_class` (via `classify_record`) and, for
    successful records, `final_answer`/`final_answer_missing`/`answer_usable`
    (via `lancet_eval.metrics`) are computed here. D-72: null questions never
    get `answer_usable` populated — `final_answer`/`final_answer_missing`
    still are, so a null question's abstention can still be read off the raw
    text.
    """
    questions = load_sample_questions(corpus_name)
    document_map = load_document_map(corpus_name)
    mapped_titles = {entry.title for entry in document_map.entries.values()}
    gold_chunks_by_question = _load_gold_chunks_by_question(gold_chunks_path)
    vector_top4_by_question = (
        _load_vector_top4_by_question(vector_top4_path)
        if vector_top4_path is not None
        else None
    )
    seed_probe_by_question = (
        _load_seed_probe(seed_probe_path)[0] if seed_probe_path is not None else None
    )
    title_to_document_id = {
        entry.title: document_id for document_id, entry in document_map.entries.items()
    }

    if journal_path is not None:
        records = load_records(journal_path)
        all_arms, records_by_key = _arms_by_question(records)
    else:
        all_arms, records_by_key = [], {}

    rows: list[DiagnosticRow] = []
    for question in questions:
        a = _question_a(question, mapped_titles)
        items: list[dict] = (
            [] if question.is_null else gold_chunks_by_question.get(question.question_id, [])
        )
        b_items, b = _question_b(items)
        if question.is_null:
            c = None
        else:
            top4 = (
                vector_top4_by_question.get(question.question_id)
                if vector_top4_by_question is not None
                else None
            )
            c = _question_c(items, top4)

        d: bool | None = None
        seed_count: int | None = None
        path_found: bool | None = None
        probe_record = (
            seed_probe_by_question.get(question.question_id)
            if seed_probe_by_question is not None
            else None
        )
        gold_document_ids = (
            set()
            if question.is_null
            else _gold_document_ids(question, title_to_document_id)
        )
        if probe_record is not None:
            seed_count = probe_record["seed_count"]
            path_found = probe_record["path_found"]
            if not question.is_null:
                d = _question_d(gold_document_ids, probe_record)

        # The graph-on record's own wire fields are what the engine measured on the
        # run itself, so each one that is present beats the offline probe (D-79).
        # None means the record predates the field; an empty list is a measured "no".
        wire = records_by_key.get((question.question_id, "graph-on"))
        wire_meta = wire.workflow_meta if wire is not None else None
        if wire_meta is not None:
            if wire_meta.graph_seed_count is not None:
                seed_count = wire_meta.graph_seed_count
            if wire_meta.graph_path_found is not None:
                path_found = wire_meta.graph_path_found
            seed_documents = wire_meta.graph_seed_document_ids
            if seed_documents is not None and not question.is_null:
                d = bool(gold_document_ids.intersection(seed_documents))

        arms: dict[str, ArmResult] = {}
        for arm in all_arms:
            record = records_by_key.get((question.question_id, arm))
            if record is None:
                arms[arm] = ArmResult(arm=arm, outcome="not_run")
                continue

            error_class = classify_record(record)
            if record.outcome != "success":
                arms[arm] = ArmResult(
                    arm=arm, outcome=record.outcome, error_class=error_class
                )
                continue

            final_answer = extract_final_answer(record.answer)
            usable = (
                None
                if question.is_null
                else _answer_usable(question, record.answer or "")
            )
            arms[arm] = ArmResult(
                arm=arm,
                outcome=record.outcome,
                error_class=error_class,
                answer_usable=usable,
                final_answer_missing=final_answer is None,
                final_answer=final_answer,
            )

        graph_off = arms.get("graph-off")
        e_answer_usable = graph_off.answer_usable if graph_off is not None else None

        in_gold_in_index_subset = (not question.is_null) and b is True

        rows.append(
            DiagnosticRow(
                question_id=question.question_id,
                question_type=question.question_type,
                is_null=question.is_null,
                a_gold_doc_in_map=a,
                b_items=b_items,
                b_gold_chunk_in_lancedb=b,
                c_gold_in_vector_top4=c,
                d_graph_seed_hit=d,
                seed_count=seed_count,
                path_found=path_found,
                e_answer_usable=e_answer_usable,
                arms=arms,
                in_gold_in_index_subset=in_gold_in_index_subset,
            )
        )

    rows.sort(key=lambda row: row.question_id)
    return rows


def _yn(value: bool | None) -> str:
    """Renders a tri-state bool as yes/no/— for the markdown table."""
    if value is None:
        return "—"
    return "yes" if value else "no"


def _cell(value: object) -> str:
    """Renders an arbitrary optional scalar as its string form or —."""
    if value is None:
        return "—"
    return str(value)


def write_table(
    rows: list[DiagnosticRow],
    out_dir: str | Path,
    *,
    label: str = "",
    journal_path: str | Path | None = None,
    gold_chunks_path: str | Path = "",
) -> None:
    """Writes `table.jsonl` (one `model_dump_json` per line) and `table.md`.

    `table.md`'s first line is `label` verbatim (composed by the caller — see
    `main`'s partial-run labelling rule); its second line is a provenance
    header naming the journal path, the gold-chunk file, and the row count.
    Never hand-edit either output; both are fully regenerated from `rows`.
    """
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    jsonl_path = out_path / "table.jsonl"
    with open(jsonl_path, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(row.model_dump_json())
            f.write("\n")

    md_path = out_path / "table.md"
    journal_display = str(journal_path) if journal_path is not None else "(none)"
    provenance = (
        f"journal={journal_display}; gold_chunks={gold_chunks_path}; "
        f"records={len(rows)}"
    )

    header_cols = [
        "question_id",
        "type",
        "a",
        "b",
        "c",
        "d",
        "e (graph-off)",
        "graph-on outcome",
        "graph-off outcome",
        "seeds",
        "path",
        "final_answer_missing (graph-off)",
    ]

    lines = [label, provenance, "", "| " + " | ".join(header_cols) + " |"]
    lines.append("|" + "|".join(["---"] * len(header_cols)) + "|")

    for row in rows:
        graph_on = row.arms.get("graph-on")
        graph_off = row.arms.get("graph-off")
        cells = [
            row.question_id,
            row.question_type,
            _yn(row.a_gold_doc_in_map),
            _yn(row.b_gold_chunk_in_lancedb),
            _yn(row.c_gold_in_vector_top4),
            _yn(row.d_graph_seed_hit),
            _yn(row.e_answer_usable),
            _cell(graph_on.outcome if graph_on is not None else None),
            _cell(graph_off.outcome if graph_off is not None else None),
            _cell(row.seed_count),
            _yn(row.path_found),
            _yn(graph_off.final_answer_missing if graph_off is not None else None),
        ]
        lines.append("| " + " | ".join(cells) + " |")

    with open(md_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
        f.write("\n")


def build_gold_coverage_rows(
    corpus_name: str,
    gold_chunks_path: str | Path,
) -> list[dict]:
    """Builds the per-question, per-evidence-title gold-coverage rows (D-61).

    Each row's `document_present_in_lancedb` comes from a live
    `inspect_lancedb --document-ids` probe (via
    `lancet_eval.identity.list_lancedb_document_ids` — the same probe the D-61
    preflight identity gate uses), intersected against the mapped
    `document_id`. It is deliberately NOT inferred from the (b) tri-state:
    `classify_evidence_item`'s `absent` state conflates "the document has zero
    matching chunks in the live store" with "the document exists but this
    specific fact is missing from its chunks", and D-59's re-ingest-candidate
    decision needs those two distinguished.
    """
    from lancet_eval.config import load_settings as load_eval_settings
    from lancet_eval.identity import list_lancedb_document_ids

    settings = load_eval_settings()
    live_documents = set(
        list_lancedb_document_ids(settings.lancedb_path).get("documents", [])
    )
    gold_chunks_by_question = _load_gold_chunks_by_question(gold_chunks_path)
    _ = load_document_map(corpus_name)  # validates the corpus has a committed map

    rows: list[dict] = []
    for question_id, items in gold_chunks_by_question.items():
        for item in items:
            document_id = item.get("document_id")
            rows.append(
                {
                    "question_id": question_id,
                    "evidence_index": item["evidence_index"],
                    "title": item["title"],
                    "document_id": document_id,
                    "document_present_in_lancedb": (
                        document_id in live_documents
                        if document_id is not None
                        else None
                    ),
                    "state": item["state"],
                }
            )
    rows.sort(key=lambda row: (row["question_id"], row["evidence_index"]))
    return rows


def write_gold_coverage(
    rows: list[dict],
    jsonl_dir: str | Path,
    md_path: str | Path,
) -> None:
    """Writes `gold_coverage.jsonl` (under `jsonl_dir`) and the coverage markdown
    summary (at `md_path`). Both are fully regenerated from `rows`; neither is
    ever hand-edited (D-61).
    """
    jsonl_out = Path(jsonl_dir)
    jsonl_out.mkdir(parents=True, exist_ok=True)
    jsonl_path = jsonl_out / "gold_coverage.jsonl"
    with open(jsonl_path, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(json.dumps(row))
            f.write("\n")

    state_counts: dict[str, int] = {}
    present_true = 0
    present_false = 0
    present_none = 0
    for row in rows:
        state_counts[row["state"]] = state_counts.get(row["state"], 0) + 1
        presence = row["document_present_in_lancedb"]
        if presence is True:
            present_true += 1
        elif presence is False:
            present_false += 1
        else:
            present_none += 1

    lines = [
        "# Gold-doc / document_map.json Coverage Table (D-61)",
        "",
        "Regenerated by `python -m lancet_eval.diagnostic coverage` — never hand-edited.",
        f"{len(rows)} evidence-item rows across all sample questions.",
        "",
        "## Per-item (b) tri-state counts",
        "",
        "| state | count |",
        "|---|---|",
    ]
    for state, count in sorted(state_counts.items()):
        lines.append(f"| {state} | {count} |")
    lines += [
        "",
        "## Document presence in LanceDB (live `--document-ids` probe)",
        "",
        "| presence | count |",
        "|---|---|",
        f"| present | {present_true} |",
        f"| absent | {present_false} |",
        f"| unmapped title (no document_id) | {present_none} |",
    ]

    md_out = Path(md_path)
    md_out.parent.mkdir(parents=True, exist_ok=True)
    with open(md_out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
        f.write("\n")


#: Ceiling on the path facts one question injects (mirrors the engine constant
#: `graph::paths::MAX_PATH_FACTS_CEILING`).
_MAX_PATH_FACTS_CEILING = 16

#: Share of the evidence budget that graph facts may use, in percent (the engine's
#: 10%).
_PATH_FACT_BUDGET_PERCENT = 10


def _rate(yes: int, n: int) -> dict:
    """`{yes, n, rate}`; the rate is `None` when `n` is 0 (never a fake 0.0)."""
    return {"yes": yes, "n": n, "rate": (yes / n) if n else None}


def _distribution(values: list[int]) -> dict[str, int]:
    """Histogram `{value: count}` with string keys in ascending numeric order."""
    counts: dict[int, int] = {}
    for value in values:
        counts[value] = counts.get(value, 0) + 1
    return {str(key): counts[key] for key in sorted(counts)}


def _nearest_rank(sorted_values: list[int], q: float) -> int | None:
    """Nearest-rank percentile of an ascending list; `None` for an empty list."""
    if not sorted_values:
        return None
    rank = max(math.ceil(q * len(sorted_values)) - 1, 0)
    return sorted_values[min(rank, len(sorted_values) - 1)]


def _median(values: list[int]) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    middle = len(ordered) // 2
    if len(ordered) % 2:
        return float(ordered[middle])
    return (ordered[middle - 1] + ordered[middle]) / 2


def _normalize_name(name: str) -> str:
    """The engine's `normalize_name`: lower-case words, no leading `the`."""
    words = re.findall(r"[^\W_]+", name.lower())
    if len(words) > 1 and words[0] == "the":
        words = words[1:]
    return " ".join(words)


def summarize_seed_probe(
    corpus_name: str,
    seed_probe_path: str | Path,
    gold_chunks_path: str | Path,
    vector_top4_path: str | Path,
) -> dict:
    """Summarises a `diag_probe --graph-seeds` run for `06.3.4.1-SEED-PROBE.md`.

    Every number in the probe write-up is computed here, not by hand: the
    seed-count distribution, match-kind shares, column (d) on G and on all
    non-null rows, path-found rate by `question_type`, hub and publisher seeds,
    degree-capped totals, candidate-chunk distributions, the composition-change
    proxy under both Task 3 options, and the D-77 cap inputs.

    Only questions the probe covers are counted. A "publisher" is any `source`
    value that appears in the corpus's gold evidence (read from the data here;
    the engine has no such list). The composition proxy compares each
    question's candidate chunks with the (c) probe's dense top-4:
    `paths_only` uses the chunks of the found paths; `paths_plus_seed_chunks`
    uses those when a path was found and the seeds' own chunks otherwise.
    """
    rows = build_rows(
        corpus_name,
        None,
        gold_chunks_path,
        vector_top4_path,
        seed_probe_path,
    )
    probe_by_question, probe_summary = _load_seed_probe(seed_probe_path)
    top4_by_question = _load_vector_top4_by_question(vector_top4_path)
    sample_questions = load_sample_questions(corpus_name)

    probed = [row for row in rows if row.question_id in probe_by_question]
    non_null = [row for row in probed if not row.is_null]
    in_g = [row for row in probed if row.in_gold_in_index_subset]

    publisher_names: set[str] = set()
    for question in sample_questions:
        for item in question.evidence_list:
            source = item.get("source")
            if source:
                publisher_names.add(_normalize_name(source))
    publisher_names.discard("")

    document_map = load_document_map(corpus_name)
    title_to_document_id = {
        entry.title: document_id for document_id, entry in document_map.entries.items()
    }
    questions_by_id = {question.question_id: question for question in sample_questions}

    degree_p95 = probe_summary.get("degree_p95") if probe_summary else None

    def is_nameless(seed: dict) -> bool:
        return not _normalize_name(seed.get("name", ""))

    def is_publisher(seed: dict) -> bool:
        return _normalize_name(seed.get("name", "")) in publisher_names

    def is_hub(seed: dict) -> bool:
        return degree_p95 is not None and seed.get("degree", 0) > degree_p95

    def d_without(selected: list[DiagnosticRow], drop) -> dict:
        """Column (d) recomputed with the seeds that `drop` selects removed."""
        yes = 0
        for row in selected:
            kept = [
                seed
                for seed in probe_by_question[row.question_id].get("seeds", [])
                if not drop(seed)
            ]
            gold = _gold_document_ids(
                questions_by_id[row.question_id], title_to_document_id
            )
            yes += int(_question_d(gold, {"seeds": kept}))
        return _rate(yes, len(selected))

    seeds_total = 0
    kind_counts: dict[str, int] = {}
    hub_seeds = 0
    publisher_seeds = 0
    publisher_hub_seeds = 0
    questions_with_hub = 0
    questions_with_publisher = 0
    capped_total = 0
    questions_with_capped = 0
    fact_tokens: list[int] = []
    one_hop_paths = 0
    two_hop_paths = 0
    nameless_seeds = 0
    nameless_question_ids: set[str] = set()
    endpoint_classes = {"both_publisher": 0, "one_publisher": 0, "neither_publisher": 0}
    questions_with_paths = 0
    questions_with_non_publisher_path = 0
    for row in probed:
        record = probe_by_question[row.question_id]
        has_hub = False
        has_publisher = False
        for seed in record.get("seeds", []):
            seeds_total += 1
            kind = seed.get("match_kind", "unknown")
            kind_counts[kind] = kind_counts.get(kind, 0) + 1
            seed_is_hub = is_hub(seed)
            seed_is_publisher = is_publisher(seed)
            nameless_seeds += int(is_nameless(seed))
            if is_nameless(seed):
                nameless_question_ids.add(row.question_id)
            hub_seeds += int(seed_is_hub)
            publisher_seeds += int(seed_is_publisher)
            publisher_hub_seeds += int(seed_is_hub and seed_is_publisher)
            has_hub = has_hub or seed_is_hub
            has_publisher = has_publisher or seed_is_publisher
        questions_with_hub += int(has_hub)
        questions_with_publisher += int(has_publisher)
        capped = record.get("degree_capped_count", 0)
        capped_total += capped
        questions_with_capped += int(capped > 0)
        publisher_by_entity = {
            seed["entity_id"]: is_publisher(seed) for seed in record.get("seeds", [])
        }
        has_path = False
        has_non_publisher_path = False
        for path in record.get("paths", []):
            fact_tokens.append(path["tokens"])
            if len(path["entities"]) == 2:
                one_hop_paths += 1
            else:
                two_hop_paths += 1
            ends = [
                publisher_by_entity.get(path["entities"][0], False),
                publisher_by_entity.get(path["entities"][-1], False),
            ]
            if all(ends):
                endpoint_classes["both_publisher"] += 1
            elif any(ends):
                endpoint_classes["one_publisher"] += 1
            else:
                endpoint_classes["neither_publisher"] += 1
            has_path = True
            has_non_publisher_path = has_non_publisher_path or not any(ends)
        questions_with_paths += int(has_path)
        questions_with_non_publisher_path += int(has_non_publisher_path)

    def candidates(record: dict, option: str) -> list[str]:
        if option == "paths_only" or record["path_found"]:
            return list(record["candidate_chunk_ids"])
        return list(record["seed_chunk_candidate_ids"])

    candidate_counts = {
        option: [
            len(candidates(probe_by_question[row.question_id], option))
            for row in probed
        ]
        for option in ("paths_only", "paths_plus_seed_chunks")
    }

    def proxy(selected: list[DiagnosticRow]) -> dict:
        result: dict[str, dict] = {}
        measured = [row for row in selected if row.question_id in top4_by_question]
        for option in ("paths_only", "paths_plus_seed_chunks"):
            outside_counts = []
            for row in measured:
                top4 = set(top4_by_question[row.question_id])
                outside = [
                    chunk_id
                    for chunk_id in candidates(
                        probe_by_question[row.question_id], option
                    )
                    if chunk_id not in top4
                ]
                outside_counts.append(len(outside))
            result[option] = {
                **_rate(sum(1 for count in outside_counts if count > 0), len(measured)),
                "outside_chunk_count_distribution": _distribution(outside_counts),
            }
        return result

    fact_tokens.sort()
    p95_tokens = _nearest_rank(fact_tokens, 0.95)
    degree_p99 = probe_summary.get("degree_p99") if probe_summary else None
    evidence_budget = (
        probe_summary.get("evidence_token_budget") if probe_summary else None
    )
    answer_budget = probe_summary.get("max_output_tokens") if probe_summary else None
    max_path_facts = None
    if p95_tokens and evidence_budget is not None and answer_budget is not None:
        room = max(evidence_budget - answer_budget, 0)
        max_path_facts = min(
            _MAX_PATH_FACTS_CEILING,
            room * _PATH_FACT_BUDGET_PERCENT // (100 * p95_tokens),
        )

    types = sorted({row.question_type for row in probed})
    return {
        "questions": len(probed),
        "non_null": len(non_null),
        "gold_in_index_subset": len(in_g),
        "question_types": {
            t: sum(1 for row in probed if row.question_type == t) for t in types
        },
        "seed_count_distribution": _distribution([
            row.seed_count or 0 for row in probed
        ]),
        "seeds_total": seeds_total,
        "match_kind_counts": dict(sorted(kind_counts.items())),
        "match_kind_shares": {
            kind: (count / seeds_total) if seeds_total else None
            for kind, count in sorted(kind_counts.items())
        },
        "d_graph_seed_hit": {
            "gold_in_index_subset": _rate(
                sum(1 for row in in_g if row.d_graph_seed_hit is True), len(in_g)
            ),
            "all_non_null": _rate(
                sum(1 for row in non_null if row.d_graph_seed_hit is True),
                len(non_null),
            ),
        },
        "path_found": {
            "overall": _rate(
                sum(1 for row in probed if row.path_found is True), len(probed)
            ),
            "all_non_null": _rate(
                sum(1 for row in non_null if row.path_found is True), len(non_null)
            ),
            "gold_in_index_subset": _rate(
                sum(1 for row in in_g if row.path_found is True), len(in_g)
            ),
            "by_question_type": {
                t: _rate(
                    sum(
                        1
                        for row in probed
                        if row.question_type == t and row.path_found is True
                    ),
                    sum(1 for row in probed if row.question_type == t),
                )
                for t in types
            },
        },
        "hub_seeds": {
            "degree_p95": degree_p95,
            "seeds_over_p95": _rate(hub_seeds, seeds_total),
            "questions_with_a_hub_seed": _rate(questions_with_hub, len(probed)),
        },
        "nameless_seeds": {
            "label": (
                "seeds whose name has no letter or digit (a degenerate entity the "
                "library now refuses; the probe ran before that guard)"
            ),
            "seeds": nameless_seeds,
            "questions": len(nameless_question_ids),
        },
        "d_graph_seed_hit_without": {
            "label": (
                "column (d) recomputed with one kind of seed removed, from the same "
                "probe output"
            ),
            "nameless_seeds": {
                "gold_in_index_subset": d_without(in_g, is_nameless),
                "all_non_null": d_without(non_null, is_nameless),
            },
            "publisher_seeds": {
                "gold_in_index_subset": d_without(in_g, is_publisher),
                "all_non_null": d_without(non_null, is_publisher),
            },
            "publisher_and_hub_seeds": {
                "gold_in_index_subset": d_without(
                    in_g, lambda seed: is_publisher(seed) or is_hub(seed)
                ),
                "all_non_null": d_without(
                    non_null, lambda seed: is_publisher(seed) or is_hub(seed)
                ),
            },
        },
        "path_endpoints": {
            "label": (
                "the two end seeds of each found path, by whether they are "
                "publisher names"
            ),
            **endpoint_classes,
            "questions_with_a_path_with_no_publisher_end": _rate(
                questions_with_non_publisher_path, questions_with_paths
            ),
        },
        "publisher_seeds": {
            "distinct_publisher_names_in_gold": len(publisher_names),
            "seeds_that_are_publishers": _rate(publisher_seeds, seeds_total),
            "questions_with_a_publisher_seed": _rate(
                questions_with_publisher, len(probed)
            ),
            "publisher_seeds_that_are_hubs": _rate(
                publisher_hub_seeds, publisher_seeds
            ),
        },
        "degree_capped": {
            "total": capped_total,
            "questions_with_any": _rate(questions_with_capped, len(probed)),
        },
        "candidate_chunks": {
            option: {
                "distribution": _distribution(counts),
                "mean": (sum(counts) / len(counts)) if counts else None,
                "median": _median(counts),
                "questions_with_none": _rate(
                    sum(1 for count in counts if count == 0), len(counts)
                ),
            }
            for option, counts in candidate_counts.items()
        },
        "composition_change_proxy": {
            "label": (
                "share of questions whose candidate chunks include a chunk outside the "
                "(c)-probe dense top-4 (a proxy, not a retrieval measurement)"
            ),
            "all_probed": proxy(probed),
            "all_non_null": proxy(non_null),
            "gold_in_index_subset": proxy(in_g),
        },
        "path_fact_tokens": {
            "paths": len(fact_tokens),
            "one_hop_paths": one_hop_paths,
            "two_hop_paths": two_hop_paths,
            "p50": _nearest_rank(fact_tokens, 0.50),
            "p95": p95_tokens,
            "max": fact_tokens[-1] if fact_tokens else None,
            "mean": (sum(fact_tokens) / len(fact_tokens)) if fact_tokens else None,
        },
        "d77_caps": {
            "degree_p99": degree_p99,
            "degree_cap": math.ceil(degree_p99) if degree_p99 is not None else None,
            "evidence_token_budget": evidence_budget,
            "answer_token_budget": answer_budget,
            "p95_fact_tokens": p95_tokens,
            "max_path_facts": max_path_facts,
            "max_path_facts_formula": (
                "min(16, floor(0.10 * (evidence_token_budget - answer_token_budget)"
                " / p95_fact_tokens))"
            ),
        },
        "probe": probe_summary,
    }


def _compose_label(label: str, journal_path: str | Path | None, row_count: int) -> str:
    """Builds the markdown line-1 label, enforcing the partial-run disclosure rule.

    When the journal header says `partial: true`, the label must contain
    `partial-run diagnostic` and an `n=` count (OBS-05: a halted/partial drive
    must never be labelled as a complete scored run). The caller's `--label`
    text is a prefix, never a substitute for this disclosure.
    """
    if journal_path is None:
        return label
    header = _load_journal_header(journal_path)
    if header is None or not header.get("partial"):
        return label
    disclosure = f"partial-run diagnostic, n={row_count}"
    if label:
        return f"{label}, {disclosure}"
    return disclosure


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: `python -m lancet_eval.diagnostic table ...`."""
    parser = argparse.ArgumentParser(prog="python -m lancet_eval.diagnostic")
    subparsers = parser.add_subparsers(dest="command", required=True)

    table_parser = subparsers.add_parser(
        "table", help="Regenerate the per-question diagnostic table."
    )
    table_parser.add_argument("--corpus", required=True)
    table_parser.add_argument("--journal", default=None)
    table_parser.add_argument("--gold-chunks", dest="gold_chunks", required=True)
    table_parser.add_argument("--vector-top4", dest="vector_top4", default=None)
    table_parser.add_argument("--seed-probe", dest="seed_probe", default=None)
    table_parser.add_argument("--out-dir", dest="out_dir", required=True)
    table_parser.add_argument("--label", default="")

    seed_summary_parser = subparsers.add_parser(
        "seed-summary",
        help="Summarise a `diag_probe --graph-seeds` run (06.3.4.1-13) as JSON.",
    )
    seed_summary_parser.add_argument("--corpus", required=True)
    seed_summary_parser.add_argument("--seed-probe", dest="seed_probe", required=True)
    seed_summary_parser.add_argument("--gold-chunks", dest="gold_chunks", required=True)
    seed_summary_parser.add_argument("--vector-top4", dest="vector_top4", required=True)
    seed_summary_parser.add_argument("--out", default=None)

    coverage_parser = subparsers.add_parser(
        "coverage",
        help="Regenerate the gold-doc vs document_map.json coverage table (D-61).",
    )
    coverage_parser.add_argument("--corpus", required=True)
    coverage_parser.add_argument("--gold-chunks", dest="gold_chunks", required=True)
    coverage_parser.add_argument("--out-dir", dest="out_dir", required=True)
    coverage_parser.add_argument("--md-path", dest="md_path", required=True)

    args = parser.parse_args(argv)

    if args.command == "table":
        rows = build_rows(
            args.corpus,
            args.journal,
            args.gold_chunks,
            args.vector_top4,
            args.seed_probe,
        )
        label = _compose_label(args.label, args.journal, len(rows))
        write_table(
            rows,
            args.out_dir,
            label=label,
            journal_path=args.journal,
            gold_chunks_path=args.gold_chunks,
        )
        return 0

    if args.command == "seed-summary":
        summary = summarize_seed_probe(
            args.corpus, args.seed_probe, args.gold_chunks, args.vector_top4
        )
        text = json.dumps(summary, indent=2, sort_keys=False, ensure_ascii=False)
        if args.out:
            out_path = Path(args.out)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            with open(out_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
                f.write("\n")
        else:
            print(text)
        return 0

    if args.command == "coverage":
        rows = build_gold_coverage_rows(args.corpus, args.gold_chunks)
        write_gold_coverage(rows, args.out_dir, args.md_path)
        return 0

    return 1


if __name__ == "__main__":
    raise SystemExit(main())
