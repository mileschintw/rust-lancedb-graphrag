"""Per-question diagnostic table: joins the live-store gold-chunk probe, the
run journal, and the corpus/document map into one regenerable yes/no table.

This module never computes ground truth itself. Column (a) comes from
`load_document_map`, column (b) comes from the `inspect_lancedb --gold-chunks`
probe output (JSONL, one line per evidence item), and per-arm outcomes come
from the run journal via `load_records`. Everything here is read-only: no
function in this module writes to the eval store, the journal, or the
document map.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from lancet_eval.corpus import GoldQuestion, load_sample_questions
from lancet_eval.journal import RunRecord, load_records
from lancet_eval.metrics import answer_usable as _answer_usable
from lancet_eval.metrics import extract_final_answer
from lancet_eval.seed import load_document_map

_D69_MIXED = "answer basis 'mixed' requires at least one cited evidence ID"
_D69_RETRIEVAL = "answer basis 'retrieval' requires at least one cited evidence ID"
_D69_MODEL_ONLY = "ModelOnly answer basis is not supported"
_MARKER_MISMATCH = "mismatch between cited_evidence_ids"
_HARNESS_TIMEOUT_ERROR_TYPES = ("StreamDeadlineExceeded", "ReadTimeout")


def classify_record(record: RunRecord) -> str | None:
    """Classifies an errored journal record into a stable D-69/timeout/transport class.

    Returns None for a non-error outcome (nothing to classify). See RESEARCH
    §B for the exact message prefixes and the fixed classification order:
    a node `error_kind == 1` (timeout) takes priority over the D-69 message
    match, and a harness-level `error_type` is checked only when no
    node-level failure explains the error.
    """
    if record.outcome != "error":
        return None

    for node_failure in record.node_failures:
        if node_failure.error_kind == 1:
            return "timeout"
        if node_failure.node_name != "GenerateAnswer":
            continue
        message = node_failure.error_message
        if message.startswith(_D69_MIXED):
            return "citation_basis_mixed"
        if message.startswith(_D69_RETRIEVAL):
            return "citation_basis_retrieval"
        if message.startswith(_D69_MODEL_ONLY):
            return "model_only_unsupported"
        if message.startswith(_MARKER_MISMATCH):
            return "citation_marker_mismatch"

    if record.error_type in _HARNESS_TIMEOUT_ERROR_TYPES:
        return "timeout"
    if record.error_type is not None:
        return "transport"

    return "other"


class DiagnosticError(Exception):
    """Raised when diagnostic table inputs are internally inconsistent.

    Never silently resolved — for example, two journal records for the same
    (question_id, arm) pair raise rather than picking one arbitrarily.
    """


class ArmResult(BaseModel):
    """Per-arm (graph-on / graph-off) outcome and quality facts for one question."""

    model_config = ConfigDict(extra="forbid")

    arm: str
    outcome: Literal["success", "error", "not_run"]
    error_class: str | None = None
    answer_usable: bool | None = None
    final_answer_missing: bool | None = None
    final_answer: str | None = None


class DiagnosticRow(BaseModel):
    """One row of the required per-question diagnostic table.

    Regenerated by `build_rows`/`write_table`; never hand-edited.
    """

    model_config = ConfigDict(extra="forbid")

    question_id: str
    question_type: str
    is_null: bool
    a_gold_doc_in_map: bool | None
    b_items: list[str] = Field(default_factory=list)
    b_gold_chunk_in_lancedb: bool | None
    c_gold_in_vector_top4: bool | None = None
    d_graph_seed_hit: bool | None = None
    seed_count: int | None = None
    path_found: bool | None = None
    e_answer_usable: bool | None = None
    arms: dict[str, ArmResult] = Field(default_factory=dict)
    in_gold_in_index_subset: bool


def _load_gold_chunks_by_question(
    gold_chunks_path: str | Path,
) -> dict[str, list[dict]]:
    """Reads the `--gold-chunks` probe JSONL, grouped by `question_id`.

    Each value is the list of per-evidence-item records for that question,
    sorted by `evidence_index` (the probe already sorts by (question_id,
    evidence_index), but the sort is repeated here so this function is
    correct even against a hand-built or reordered fixture).
    """
    by_question: dict[str, list[dict]] = {}
    path = Path(gold_chunks_path)
    with open(path, encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue
            record = json.loads(stripped)
            by_question.setdefault(record["question_id"], []).append(record)
    for records in by_question.values():
        records.sort(key=lambda r: r["evidence_index"])
    return by_question


def _load_journal_header(journal_path: str | Path) -> dict | None:
    """Reads only the first line of a journal file, returning it if it is a header.

    Returns None if the file does not exist, is empty, or its first line is
    not a `{"type": "header", ...}` record.
    """
    path = Path(journal_path)
    if not path.is_file():
        return None
    with open(path, encoding="utf-8") as f:
        first_line = f.readline().strip()
    if not first_line:
        return None
    try:
        data = json.loads(first_line)
    except json.JSONDecodeError:
        return None
    if isinstance(data, dict) and data.get("type") == "header":
        return data
    return None


def _arms_by_question(
    records: list[RunRecord],
) -> tuple[list[str], dict[tuple[str, str], RunRecord]]:
    """Indexes journal records by (question_id, arm), raising on duplicates.

    Returns the sorted list of distinct arm names seen anywhere in the
    journal (used to synthesize `not_run` placeholders for questions with no
    record for a given arm) alongside the (question_id, arm) -> record index.
    """
    by_key: dict[tuple[str, str], RunRecord] = {}
    arms: set[str] = set()
    for record in records:
        key = (record.question_id, record.graph_arm)
        if key in by_key:
            raise DiagnosticError(
                f"duplicate journal record for question_id={record.question_id!r} "
                f"arm={record.graph_arm!r}; refusing to silently choose one"
            )
        by_key[key] = record
        arms.add(record.graph_arm)
    return sorted(arms), by_key


def _question_a(question: GoldQuestion, mapped_titles: set[str]) -> bool | None:
    """Column (a): every gold evidence title has a document_map entry.

    None for null questions (no evidence to check).
    """
    if question.is_null:
        return None
    return all(item.get("title") in mapped_titles for item in question.evidence_list)


def _question_b(
    question: GoldQuestion, gold_chunks_by_question: dict[str, list[dict]]
) -> tuple[list[str], bool | None]:
    """Column (b): every evidence item's gold chunk is `in_chunk` (D-63).

    None for null questions. b_items lists the raw per-item states in
    evidence_index order.
    """
    if question.is_null:
        return [], None
    items = gold_chunks_by_question.get(question.question_id, [])
    states = [item["state"] for item in items]
    if not states:
        return states, None
    return states, all(state == "in_chunk" for state in states)


def build_rows(
    corpus_name: str,
    journal_path: str | Path | None,
    gold_chunks_path: str | Path,
) -> list[DiagnosticRow]:
    """Builds one DiagnosticRow per question in `corpus_name`'s sample.

    Columns (c)/(d)/seed_count/path_found are left `None` here; later tasks in
    this phase compute them from additional inputs this task does not yet
    have. Per-arm `error_class` (via `classify_record`) and, for successful
    records, `final_answer`/`final_answer_missing`/`answer_usable` (via
    `lancet_eval.metrics`) are computed here. D-72: null questions never get
    `answer_usable` populated — `final_answer`/`final_answer_missing` still
    are, so a null question's abstention can still be read off the raw text.
    """
    questions = load_sample_questions(corpus_name)
    document_map = load_document_map(corpus_name)
    mapped_titles = {entry.title for entry in document_map.entries.values()}
    gold_chunks_by_question = _load_gold_chunks_by_question(gold_chunks_path)

    if journal_path is not None:
        records = load_records(journal_path)
        all_arms, records_by_key = _arms_by_question(records)
    else:
        all_arms, records_by_key = [], {}

    rows: list[DiagnosticRow] = []
    for question in questions:
        a = _question_a(question, mapped_titles)
        b_items, b = _question_b(question, gold_chunks_by_question)

        arms: dict[str, ArmResult] = {}
        for arm in all_arms:
            record = records_by_key.get((question.question_id, arm))
            if record is None:
                arms[arm] = ArmResult(arm=arm, outcome="not_run")
                continue

            error_class = classify_record(record)
            if record.outcome != "success":
                arms[arm] = ArmResult(
                    arm=arm, outcome=record.outcome, error_class=error_class
                )
                continue

            final_answer = extract_final_answer(record.answer)
            usable = (
                None
                if question.is_null
                else _answer_usable(question, record.answer or "")
            )
            arms[arm] = ArmResult(
                arm=arm,
                outcome=record.outcome,
                error_class=error_class,
                answer_usable=usable,
                final_answer_missing=final_answer is None,
                final_answer=final_answer,
            )

        graph_off = arms.get("graph-off")
        e_answer_usable = graph_off.answer_usable if graph_off is not None else None

        in_gold_in_index_subset = (not question.is_null) and b is True

        rows.append(
            DiagnosticRow(
                question_id=question.question_id,
                question_type=question.question_type,
                is_null=question.is_null,
                a_gold_doc_in_map=a,
                b_items=b_items,
                b_gold_chunk_in_lancedb=b,
                e_answer_usable=e_answer_usable,
                arms=arms,
                in_gold_in_index_subset=in_gold_in_index_subset,
            )
        )

    rows.sort(key=lambda row: row.question_id)
    return rows


def _yn(value: bool | None) -> str:
    """Renders a tri-state bool as yes/no/— for the markdown table."""
    if value is None:
        return "—"
    return "yes" if value else "no"


def _cell(value: object) -> str:
    """Renders an arbitrary optional scalar as its string form or —."""
    if value is None:
        return "—"
    return str(value)


def write_table(
    rows: list[DiagnosticRow],
    out_dir: str | Path,
    *,
    label: str = "",
    journal_path: str | Path | None = None,
    gold_chunks_path: str | Path = "",
) -> None:
    """Writes `table.jsonl` (one `model_dump_json` per line) and `table.md`.

    `table.md`'s first line is `label` verbatim (composed by the caller — see
    `main`'s partial-run labelling rule); its second line is a provenance
    header naming the journal path, the gold-chunk file, and the row count.
    Never hand-edit either output; both are fully regenerated from `rows`.
    """
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    jsonl_path = out_path / "table.jsonl"
    with open(jsonl_path, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(row.model_dump_json())
            f.write("\n")

    md_path = out_path / "table.md"
    journal_display = str(journal_path) if journal_path is not None else "(none)"
    provenance = (
        f"journal={journal_display}; gold_chunks={gold_chunks_path}; "
        f"records={len(rows)}"
    )

    header_cols = [
        "question_id",
        "type",
        "a",
        "b",
        "c",
        "d",
        "e (graph-off)",
        "graph-on outcome",
        "graph-off outcome",
        "seeds",
        "path",
        "final_answer_missing (graph-off)",
    ]

    lines = [label, provenance, "", "| " + " | ".join(header_cols) + " |"]
    lines.append("|" + "|".join(["---"] * len(header_cols)) + "|")

    for row in rows:
        graph_on = row.arms.get("graph-on")
        graph_off = row.arms.get("graph-off")
        cells = [
            row.question_id,
            row.question_type,
            _yn(row.a_gold_doc_in_map),
            _yn(row.b_gold_chunk_in_lancedb),
            _yn(row.c_gold_in_vector_top4),
            _yn(row.d_graph_seed_hit),
            _yn(row.e_answer_usable),
            _cell(graph_on.outcome if graph_on is not None else None),
            _cell(graph_off.outcome if graph_off is not None else None),
            _cell(row.seed_count),
            _yn(row.path_found),
            _yn(graph_off.final_answer_missing if graph_off is not None else None),
        ]
        lines.append("| " + " | ".join(cells) + " |")

    with open(md_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
        f.write("\n")


def _compose_label(label: str, journal_path: str | Path | None, row_count: int) -> str:
    """Builds the markdown line-1 label, enforcing the partial-run disclosure rule.

    When the journal header says `partial: true`, the label must contain
    `partial-run diagnostic` and an `n=` count (OBS-05: a halted/partial drive
    must never be labelled as a complete scored run). The caller's `--label`
    text is a prefix, never a substitute for this disclosure.
    """
    if journal_path is None:
        return label
    header = _load_journal_header(journal_path)
    if header is None or not header.get("partial"):
        return label
    disclosure = f"partial-run diagnostic, n={row_count}"
    if label:
        return f"{label}, {disclosure}"
    return disclosure


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: `python -m lancet_eval.diagnostic table ...`."""
    parser = argparse.ArgumentParser(prog="python -m lancet_eval.diagnostic")
    subparsers = parser.add_subparsers(dest="command", required=True)

    table_parser = subparsers.add_parser(
        "table", help="Regenerate the per-question diagnostic table."
    )
    table_parser.add_argument("--corpus", required=True)
    table_parser.add_argument("--journal", default=None)
    table_parser.add_argument("--gold-chunks", dest="gold_chunks", required=True)
    table_parser.add_argument("--out-dir", dest="out_dir", required=True)
    table_parser.add_argument("--label", default="")

    args = parser.parse_args(argv)

    if args.command == "table":
        rows = build_rows(args.corpus, args.journal, args.gold_chunks)
        label = _compose_label(args.label, args.journal, len(rows))
        write_table(
            rows,
            args.out_dir,
            label=label,
            journal_path=args.journal,
            gold_chunks_path=args.gold_chunks,
        )
        return 0

    return 1


if __name__ == "__main__":
    raise SystemExit(main())
